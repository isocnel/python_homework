books = [
    (1, "Изучаем Python. Программирование игр, визуализация данных, веб-приложения", 2017, "Эрик Мэтиз"),
    (2, "Автоматизация рутинных задач с помощью Python. Практическое руководство для начинающих", 2016, "Эл Свейгарт"),
    (3, "Грокаем алгоритмы. Иллюстрированное пособие для программистов и любопытствующих", 2017, "Адитья Бхаргава"),
    (4, "Эффективный Python. Конкретные способы улучшить свой код", 2015, "Бретт Слаткин"),
    (5, "Чистый Python. Тонкости программирования для профи", 2018, "Дэн Бейдер")
]

# словарь для быстрого поиска книг по id
books_by_id = {}

for book in books:
    books_by_id[book[0]] = book

# множество уникальных авторов
authors = set()

for book in books:
    authors.add(book[3])

# Вывод всех книг
def show_books():
    print("\nСписок книг по программированию:")

    for book in books:
        print(f"ID: {book[0]} | Название: {book[1]} | Год: {book[2]} | Автор: {book[3]}")

# добавление новой книги
def add_book(book_id, title, year, author):
    if book_id in books_by_id:
        print(f"Книга с ID {book_id} уже существует")
    else:
        new_book = (book_id, title, year, author)

        books.append(new_book)
        books_by_id[book_id] = new_book
        authors.add(author)

        print(f"Книга «{title}» добавлена")

# поиск книги по id
def find_book(book_id):
    if book_id in books_by_id:
        print("Найдена книга:", books_by_id[book_id])
    else:
        print(f"Книга с ID {book_id} не найдена")

show_books()

print("\nПоиск книг:")
find_book(3)
find_book(10)

print("\nДобавление книг:")
add_book(6, "Python. К вершинам мастерства. Лаконичное и эффективное программирование", 2016, "Лучано Рамальо")
add_book(6, "Python для сложных задач. Наука о данных и машинное обучение", 2018, "Джейк Вандер Плас")

print("\nДобавление книг:")
add_book(7, "Большая книга проектов Python", 2021, "Эл Свейгарт")

show_books()

print("\nУникальные авторы:")
for author in authors:
    print(author)

"""Список (list) используется для хранения книг, потому что его можно изменять и добавлять новые записи. Каждая книга хранится в кортеже (tuple), так как у записи есть фиксированная структура из ID, названия, года издания и автора. Словарь (dict) нужен для быстрого поиска книги по ID, который используется в качестве ключа. Множество (set) хранит уникальных авторов и автоматически не допускает повторений, это видно при добавлении книги Эла Свейгарта.

"""