class Money:
    __slots__ = ('amount', 'currency')

    def __init__(self, amount, currency):
        # запрещает запись после создания
        object.__setattr__(self, 'amount', amount)
        object.__setattr__(self, 'currency', currency)

    def __setattr__(self, name, value):
        # после создания поля менять нельзя
        raise AttributeError('Money is immutable')

    def __eq__(self, other):
        if not isinstance(other, Money):
            return NotImplemented
        return self.amount == other.amount and self.currency == other.currency

    def __hash__(self):
        # хеш от тех же полей
        return hash((self.amount, self.currency))

    def __add__(self, other):
        if not isinstance(other, Money):
            return NotImplemented
        if self.currency != other.currency:
            raise ValueError('нельзя складывать разные валюты: %s и %s' % (self.currency, other.currency))
        return Money(self.amount + other.amount, self.currency)

    def __repr__(self):
        return 'Money(%d, %r)' % (self.amount, self.currency)


def total_by_currency(payments):
    result = {}
    for m in payments:
        if m.currency in result:
            result[m.currency] = result[m.currency] + m
        else:
            result[m.currency] = m
    return result


