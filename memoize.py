def memoize(func):
    cache = {}

    def wrapper(*args, **kwargs):
        try:
            key = (args, tuple(sorted(kwargs.items())))
            hash(key)
        except TypeError:
            # нехешируемые аргументы без кэша
            return func(*args, **kwargs)

        if key in cache:
            wrapper.hits += 1
            return cache[key]

        wrapper.misses += 1
        result = func(*args, **kwargs)
        cache[key] = result
        return result

    wrapper.hits = 0
    wrapper.misses = 0

    def cache_clear():
        cache.clear()
        wrapper.hits = 0
        wrapper.misses = 0

    wrapper.cache_clear = cache_clear
    wrapper.__name__ = func.__name__
    wrapper.__doc__ = func.__doc__
    return wrapper


