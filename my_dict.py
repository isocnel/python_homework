class MyDict:
    def __init__(self, size=8):
        self._buckets = [[] for _ in range(size)]
        self._len = 0

    def _index(self, key):
        return hash(key) % len(self._buckets)

    def _find(self, key):
        idx = self._index(key)
        bucket = self._buckets[idx]
        for i, (k, v) in enumerate(bucket):
            if k == key:
                return idx, i
        return idx, None

    def __setitem__(self, key, value):
        idx, pos = self._find(key)
        if pos is not None:
            self._buckets[idx][pos] = (key, value)
        else:
            self._buckets[idx].append((key, value))
            self._len += 1
            if self._len > 2 / 3 * len(self._buckets):
                self._resize()

    def __getitem__(self, key):
        idx, pos = self._find(key)
        if pos is None:
            raise KeyError(key)
        return self._buckets[idx][pos][1]

    def __delitem__(self, key):
        idx, pos = self._find(key)
        if pos is None:
            raise KeyError(key)
        bucket = self._buckets[idx]
        self._buckets[idx] = bucket[:pos] + bucket[pos + 1:]
        self._len -= 1

    def __contains__(self, key):
        _, pos = self._find(key)
        return pos is not None

    def __len__(self):
        return self._len

    def get(self, key, default=None):
        idx, pos = self._find(key)
        if pos is None:
            return default
        return self._buckets[idx][pos][1]

    def _resize(self):
        old_buckets = self._buckets
        self._buckets = [[] for _ in range(len(old_buckets) * 2)]
        for bucket in old_buckets:
            for k, v in bucket:
                idx = self._index(k)
                self._buckets[idx].append((k, v))

    def stats(self):
        longest = 0
        for bucket in self._buckets:
            if len(bucket) > longest:
                longest = len(bucket)
        return (len(self._buckets), self._len, longest)

    def __repr__(self):
        parts = []
        for bucket in self._buckets:
            for k, v in bucket:
                parts.append(repr(k) + ': ' + repr(v))
        return 'MyDict({' + ', '.join(parts) + '})'

